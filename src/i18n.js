export function strings(lang) {
  return STRINGS[lang === 'he' ? 'he' : 'en'];
}

export function timeAgo(iso, lang) {
  const s = strings(lang).ago;
  const sec = Math.max(0, (Date.now() - new Date(iso).getTime()) / 1000);
  if (sec < 60) return s.now;
  if (sec < 3600) return s.m(Math.floor(sec / 60));
  if (sec < 86400) return s.h(Math.floor(sec / 3600));
  return s.d(Math.floor(sec / 86400));
}
